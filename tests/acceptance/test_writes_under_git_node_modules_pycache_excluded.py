"""Writes under .git, node_modules, __pycache__ excluded.

Expected: None of those files appear among the file changes
Source: "always `.git/`; `node_modules/`, `.venv/`, `venv/`, `__pycache__/`, `target/`, `dist/`, `build/`, `.next/`"
"""

from _helpers.driver import Env, cli_tty
import os, json, re, time, subprocess

def test_writes_under_git_node_modules_pycache_excluded():
    e = Env(git=True); e.init()
    p = e.record("mkdir -p node_modules/x __pycache__; echo 1 > .git/zz; echo 1 > node_modules/x/a.js; echo 1 > __pycache__/a.pyc")
    assert "0 created / 0 modified / 0 deleted" in p.stdout, p.stdout
